-- =====================================================================
-- СПРАВОЧНИК КАРТОЧЕК 1С (для выбора QR при заведении сотрудника)
-- Запустить ОДИН РАЗ в Supabase Dashboard → SQL Editor.
-- Безопасно к повторному запуску (idempotent).
-- =====================================================================
-- Сюда GitHub Action приватного репозитория yahya-yaros-data ежедневно
-- заливает карточки физлиц из 1С: кто есть в базе и какой у него UIN.
-- Нужно затем, чтобы админ в форме заведения сотрудника ВЫБИРАЛ человека
-- из списка, а не вставлял GUID руками. Опечатка в GUID = продажи уходят
-- не тому человеку, а заметить это можно очень нескоро.
--
-- Заливаются только карточки НЕ помеченные на удаление и с заполненным UIN:
-- у человека бывает старая карточка в папке «удаленные» с другим UIN
-- (например у Алимовой активная 388 и удалённая 414), и показывать обе
-- в списке — верный способ привязать не ту.

create table if not exists public.qr_cards (
  uin             text        primary key,   -- реквизит «UIN» карточки физлица = profiles.qr_id
  code            integer,                   -- код карточки в 1С (369, 381, …)
  full_name       text        not null,
  folder          text,                      -- папка справочника («Официанты» и т.п.)
  is_front_office boolean     not null default false,
  updated_at      timestamptz not null default now()
);

comment on table public.qr_cards is
  'Карточки физлиц из 1С ЯРОС для выбора QR при заведении сотрудника. Заливает GitHub Action. Только активные карточки с заполненным UIN.';
comment on column public.qr_cards.is_front_office is
  'Реквизит «Официант» 1С — на форме подписан «Выводить»: карточка показывается в списке выбора на кассе. У официантов с QR он СНЯТ, стоит у касс и администраторов.';

create index if not exists qr_cards_name on public.qr_cards (full_name);

alter table public.qr_cards enable row level security;

-- ---------------------------------------------------------------------
-- ⚠ ЧИТАЮТ ТОЛЬКО АДМИНЫ — и это не перестраховка.
-- UIN это то, что зашито в QR продавца. Кто знает чужой UIN, тот может
-- нарисовать чужой бейдж и сканировать его — продажи уйдут не тому.
-- Продавцу список карточек не нужен: свой код он видит на своём бейдже.
-- ---------------------------------------------------------------------
drop policy if exists qr_cards_read on public.qr_cards;
create policy qr_cards_read on public.qr_cards
  for select using (public.is_admin());

-- Политик на запись нет: пишет только service_role (ключ в секретах Action).

